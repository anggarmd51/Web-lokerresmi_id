BEGIN;
CREATE FUNCTION pg_temp.assert_true(ok boolean, label text) RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  IF ok IS DISTINCT FROM true THEN RAISE EXCEPTION 'GAGAL: %', label; END IF;
  RAISE NOTICE 'LULUS: %', label;
END $$;
CREATE FUNCTION pg_temp.expect_denied(statement text, label text) RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  BEGIN
    EXECUTE statement;
  EXCEPTION WHEN insufficient_privilege THEN
    RAISE NOTICE 'LULUS ditolak: %', label;
    RETURN;
  END;
  RAISE EXCEPTION 'GAGAL: operasi seharusnya ditolak: %', label;
END $$;
SELECT pg_temp.assert_true(NOT EXISTS (
  SELECT 1 FROM pg_policies WHERE policyname LIKE 'unknown_legacy_%'
), 'policy permisif tak dikenal terhapus');

SET LOCAL ROLE anon;
SELECT set_config('request.jwt.claims', '{"role":"anon"}', true);
SELECT pg_temp.assert_true(NOT public.is_lokerresmi_admin(), 'anon bukan admin');
SELECT pg_temp.assert_true((SELECT count(*) = 1 FROM public.jobs), 'anon membaca jobs');
INSERT INTO public.cv_orders(name, whatsapp, package, status, date)
VALUES ('Publik', '081234', 'ATS', 'Menunggu Review', CURRENT_DATE);
