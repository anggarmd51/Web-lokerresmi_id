SELECT pg_temp.expect_denied('DELETE FROM public.cv_orders', 'anon tidak menghapus pesanan');
SELECT pg_temp.expect_denied('TRUNCATE public.cv_orders', 'anon tidak truncate');
SELECT pg_temp.expect_denied('INSERT INTO public.jobs(title) VALUES (''Palsu'')', 'anon tidak membuat jobs');
SELECT pg_temp.expect_denied('UPDATE public.jobs SET title = ''Palsu''', 'anon tidak mengubah jobs');
SELECT pg_temp.expect_denied('DELETE FROM public.jobs', 'anon tidak menghapus jobs');
