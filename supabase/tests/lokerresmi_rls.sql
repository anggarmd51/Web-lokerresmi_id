CREATE ROLE anon NOLOGIN;
CREATE ROLE authenticated NOLOGIN;
CREATE ROLE service_role NOLOGIN BYPASSRLS;
CREATE SCHEMA auth;
GRANT USAGE ON SCHEMA auth, public TO anon, authenticated, service_role;
CREATE FUNCTION auth.jwt() RETURNS jsonb LANGUAGE sql STABLE AS $$
  SELECT NULLIF(current_setting('request.jwt.claims', true), '')::jsonb;
$$;
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$
  SELECT (auth.jwt() ->> 'sub')::uuid;
$$;
CREATE TABLE public.jobs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL, company text, location text, type text, salary text,
  category text, status text, featured boolean, urgent boolean, "desc" text,
  requirements jsonb, "applyType" text, "applyTarget" text,
  "applicantsCount" integer, created_at timestamptz DEFAULT now()
);
CREATE TABLE public.cv_orders (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz DEFAULT now(), client_name text,
  whatsapp text NOT NULL, package text NOT NULL,
  status text DEFAULT 'Menunggu Review', date date DEFAULT current_date,
  name text NOT NULL
);
-- Bentuk lama permisif termasuk policy dengan nama tidak dikenal dan column ACL.
GRANT ALL ON public.jobs, public.cv_orders TO PUBLIC, anon, authenticated, service_role;
GRANT SELECT(name), UPDATE(status) ON public.cv_orders TO PUBLIC, anon;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO PUBLIC, anon, authenticated, service_role;
ALTER TABLE public.jobs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.cv_orders ENABLE ROW LEVEL SECURITY;
CREATE POLICY unknown_legacy_jobs ON public.jobs FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY unknown_legacy_orders ON public.cv_orders FOR ALL USING (true) WITH CHECK (true);
