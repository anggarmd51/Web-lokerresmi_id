#!/usr/bin/env bash
set -euo pipefail
DB=local_lokerresmi_verified_test
sudo -u postgres dropdb --if-exists "$DB" >/dev/null
sudo -u postgres createdb "$DB"
cleanup(){ sudo -u postgres dropdb --if-exists "$DB" >/dev/null; }
trap cleanup EXIT
sudo -u postgres psql -X "$DB" <<'SQL'
DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='anon') THEN CREATE ROLE anon NOLOGIN; END IF; END $$;
DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='authenticated') THEN CREATE ROLE authenticated NOLOGIN; END IF; END $$;
DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='service_role') THEN CREATE ROLE service_role NOLOGIN BYPASSRLS; END IF; END $$;
CREATE SCHEMA auth;
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$ SELECT nullif(current_setting('request.jwt.claims',true)::jsonb->>'sub','')::uuid $$;
CREATE FUNCTION auth.jwt() RETURNS jsonb LANGUAGE sql STABLE AS $$ SELECT COALESCE(current_setting('request.jwt.claims',true),'{}')::jsonb $$;
CREATE TABLE public.cv_orders (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, created_at timestamptz NOT NULL DEFAULT now(), client_name text,
 whatsapp text NOT NULL, package text NOT NULL, status text DEFAULT 'Pending', date text, name text
);
GRANT USAGE ON SCHEMA public,auth TO anon,authenticated;
GRANT USAGE,SELECT ON SEQUENCE public.cv_orders_id_seq TO anon,authenticated;
SQL
sudo -u postgres psql -X -v ON_ERROR_STOP=1 "$DB" < supabase/migrations/20261017000100_lokerresmi_admin_predicate.sql
sudo -u postgres psql -X -v ON_ERROR_STOP=1 "$DB" < supabase/migrations/20261017000300_lokerresmi_cv_orders_rls.sql
sudo -u postgres psql -X -v ON_ERROR_STOP=1 "$DB" < supabase/migrations/20261022000100_verified_purchase.sql
sudo -u postgres psql -X -v ON_ERROR_STOP=1 "$DB" < supabase/tests/verified_purchase.sql
